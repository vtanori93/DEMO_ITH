test('un navegador que bloquea el almacenamiento conserva los ajustes durante la sesión', async ({ page }) => {
  await page.addInitScript(() => {
    Storage.prototype.setItem = () => { throw new DOMException('Bloqueado', 'QuotaExceededError') }
  })
  await page.goto('/monitor')
  await page.getByRole('button', { name: 'Personalizar indicadores', exact: true }).click()
  const dialog = page.getByRole('dialog', { name: 'Personalizar indicadores', exact: true })
  await dialog.getByLabel('Nombre del indicador', { exact: true }).fill('Motor en esta sesión')
  await dialog.getByRole('button', { name: 'Guardar personalización', exact: true }).click()
  await expect(page.getByTestId('indicator-temperature').getByRole('heading', { name: 'Motor en esta sesión' })).toBeVisible()
  await expect(page.getByText('El navegador no permitió guardar', { exact: false })).toBeVisible()
  await page.getByRole('button', { name: 'Probar demo', exact: true }).click()
  await expect(page.getByTestId('value-temperature')).not.toHaveText('—')
})

test('sincroniza las preferencias entre pestañas y recupera una configuración dañada', async ({ page, context }) => {
  await page.goto('/monitor')
  const other = await context.newPage()
  await other.goto('/monitor')
  await expect(other.getByTestId('indicator-temperature')).toBeVisible()
  await page.getByRole('button', { name: 'Personalizar indicadores', exact: true }).click()
  const dialog = page.getByRole('dialog', { name: 'Personalizar indicadores', exact: true })
  await dialog.getByLabel('Nombre del indicador', { exact: true }).fill('Motor compartido')
  await dialog.getByRole('button', { name: 'Guardar personalización', exact: true }).click()
  await expect(other.getByTestId('indicator-temperature').getByRole('heading', { name: 'Motor compartido' })).toBeVisible()
  await other.evaluate(() => localStorage.setItem('voltio.indicators.v1', '{incorrecto'))
  await expect(page.getByTestId('indicator-temperature').getByRole('heading', { name: 'Temperatura', exact: true })).toBeVisible()
  await other.reload()
  await expect(other.getByTestId('indicator-temperature').getByRole('heading', { name: 'Temperatura', exact: true })).toBeVisible()
  await expect(other.getByTestId('indicator-temperature')).toHaveAttribute('data-style', 'arc')
  await other.close()
})
