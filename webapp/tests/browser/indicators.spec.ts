test('valida el borrador, permite cancelar y restaura el foco al cerrar con Escape', async ({ page }) => {
  await page.goto('/monitor')
  const trigger = page.getByRole('button', { name: 'Personalizar Temperatura', exact: true })
  await trigger.click()
  const dialog = page.getByRole('dialog', { name: 'Personalizar indicadores', exact: true })
  const save = dialog.getByRole('button', { name: 'Guardar personalización', exact: true })
  await dialog.getByLabel('Nombre del indicador', { exact: true }).fill('')
  await expect(save).toBeDisabled()
  await expect(dialog.getByRole('alert')).toContainText('Escribe un nombre')
  await dialog.getByLabel('Nombre del indicador', { exact: true }).fill('Motor')
  await dialog.getByLabel('Código HEX', { exact: true }).fill('bad')
  await expect(save).toBeDisabled()
  await expect(dialog.getByRole('alert')).toContainText('Introduce un color')
  await dialog.getByLabel('Código HEX', { exact: true }).fill('#168b89')
  await dialog.getByRole('switch', { name: 'Activar avisos visuales' }).check()
  await dialog.getByLabel('Umbral inferior (°C)', { exact: true }).fill('90')
  await dialog.getByLabel('Umbral superior (°C)', { exact: true }).fill('60')
  await expect(dialog.getByRole('alert')).toContainText('inferior debe ser menor')
  await expect(save).toBeDisabled()
  await dialog.getByRole('button', { name: 'Voltaje V', exact: true }).click()
  await expect(save).toBeDisabled()
  await dialog.getByRole('button', { name: /Temperatura °C/ }).click()
  await dialog.getByLabel('Umbral inferior (°C)', { exact: true }).fill('-31')
  await expect(save).toBeDisabled()
  await dialog.getByLabel('Umbral inferior (°C)', { exact: true }).fill('-30')
  await dialog.getByLabel('Umbral superior (°C)', { exact: true }).fill('100')
  await expect(save).toBeEnabled()
  await dialog.getByRole('button', { name: 'Cancelar', exact: true }).click()
  await expect(page.getByTestId('indicator-temperature').getByRole('heading', { name: 'Temperatura', exact: true })).toBeVisible()
  await expect(trigger).toBeFocused()
  await trigger.click()
  await page.keyboard.press('Escape')
  await expect(dialog).toBeHidden()
  await expect(trigger).toBeFocused()
})

